"""Turn the raw CSVs into report-ready markdown and rewrite docs/RESULTS.md.

Aggregates per-seed results into mean +/- s.d. per algorithm, computes sample
efficiency from the training logs, and folds in the robustness sweep. Run it
after every batch of runs; it is idempotent.

    python eval/evaluate.py --all --episodes 20
    python eval/robustness.py --all
    python eval/make_tables.py
"""
import argparse
import json
import re
from collections import defaultdict
from pathlib import Path

import numpy as np
import pandas as pd

MAIN_ENV = "Ant-v5"
THRESHOLD = 1000.0  # Ant return threshold used for the sample-efficiency column

PRETTY = {
    "ppo": "PPO", "sac": "SAC", "a2c": "A2C", "reinforce": "REINFORCE (ours)",
    "scripted_gait": "Scripted trot", "random": "Random policy",
}
ORDER = ["ppo", "sac", "a2c", "reinforce", "scripted_gait", "random"]


def parse_name(name: str):
    """'ppo_s0' -> ('ppo', None).  'reinforce_s0_full_none' -> ('reinforce', 'full_none').

    Algorithm names may carry a hyphenated environment suffix, as in
    'reinforce-halfcheetah_s1_to-go_none'.
    """
    m = re.match(r"^([a-z0-9-]+)_s(\d+)(?:_(.+))?$", name)
    if not m:
        return name, None
    return m.group(1), m.group(3)


def run_config(runs_dir: str, name: str) -> dict:
    cfg = Path(runs_dir) / name / "config.json"
    if cfg.exists():
        try:
            return json.loads(cfg.read_text())
        except Exception:
            pass
    return {}


def fmt(mean, std=None, dp=1):
    if mean is None or (isinstance(mean, float) and np.isnan(mean)):
        return ""
    if std is None or np.isnan(std):
        return f"{mean:,.{dp}f}"
    return f"{mean:,.{dp}f} &plusmn; {std:,.{dp}f}"


def steps_to_threshold(run_dir: Path, threshold: float = THRESHOLD):
    """First environment step at which the 20-episode moving average clears
    the threshold. None if it never does."""
    cfg_path = run_dir / "config.json"
    if not cfg_path.exists():
        return None
    algo = json.loads(cfg_path.read_text()).get("algo")

    if algo == "reinforce":
        p = run_dir / "progress.csv"
        if not p.exists():
            return None
        df = pd.read_csv(p).rename(columns={"timesteps": "steps",
                                            "mean_ep_return": "r"})
    else:
        frames = []
        for csv_path in sorted((run_dir / "monitor").glob("*.csv")):
            try:
                d = pd.read_csv(csv_path, skiprows=1)
            except Exception:
                continue
            if {"r", "l", "t"} <= set(d.columns) and len(d):
                d = d.sort_values("t")
                d["steps"] = d["l"].cumsum()
                frames.append(d[["steps", "r"]])
        if not frames:
            return None
        n = len(frames)
        df = pd.concat(frames).sort_values("steps")
        df["steps"] = df["steps"] * n

    if len(df) < 5:
        return None
    smooth = df["r"].rolling(20, min_periods=5).mean()
    hit = df["steps"][smooth >= threshold]
    return float(hit.iloc[0]) if len(hit) else None


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--metrics", default="docs/metrics.csv")
    ap.add_argument("--robustness", default="docs/robustness.csv")
    ap.add_argument("--runs", default="runs")
    ap.add_argument("--out", default="docs/RESULTS.md")
    args = ap.parse_args()

    mpath = Path(args.metrics)
    if not mpath.exists():
        print(f"[tables] {mpath} not found. Run eval/evaluate.py --all first.")
        return
    metrics = pd.read_csv(mpath)

    # ---- group per-seed rows by algorithm -------------------------------
    groups, ablations, abl_env = defaultdict(list), defaultdict(list), None
    for _, row in metrics.iterrows():
        name = str(row["name"])
        algo, variant = parse_name(name)
        cfg = run_config(args.runs, name)
        env = cfg.get("env", MAIN_ENV)
        if env != MAIN_ENV:
            # a different environment: returns are not comparable, so it only
            # belongs in the ablation section
            key = f"{cfg.get('returns', '?')}_{cfg.get('baseline', '?')}"
            ablations[key].append(row)
            abl_env = env
            continue
        if variant:
            # an ablation variant run on the MAIN env. Superseded by the runs
            # on the dedicated ablation environment, and mixing the two would
            # average returns from different reward scales into one cell.
            continue
        groups[algo].append(row)

    eff = {}
    for run_dir in sorted(Path(args.runs).glob("*")):
        if run_dir.is_dir():
            eff[run_dir.name] = steps_to_threshold(run_dir)

    lines = ["# Results", "",
             "Generated by `eval/make_tables.py`. Do not hand-edit; re-run it.",
             "",
             f"Sample efficiency column: first environment step at which the "
             f"20-episode moving average of training return reaches "
             f"{THRESHOLD:,.0f}.", "",
             "> **Reading the return column.** `Ant-v5` pays a healthy bonus of "
             "+1 per step, so simply surviving 1000 steps scores about 1000 "
             "without moving. Always read return together with forward "
             "velocity.", "",
             "## Main table", "",
             "| Policy | Seeds | Return | Fwd velocity (m/s) | Survival steps | Mean sq. action | Steps to return 1000 |",
             "|---|---|---|---|---|---|---|"]

    for algo in ORDER:
        rows = groups.get(algo)
        if not rows:
            continue
        df = pd.DataFrame(rows)
        n = len(df)
        e = [eff.get(str(r["name"])) for _, r in df.iterrows()]
        e = [v for v in e if v is not None]
        eff_cell = f"{np.mean(e):,.0f}" if e else ("never" if algo not in
                                                   ("scripted_gait", "random") else "n/a")
        lines.append(
            f"| {PRETTY.get(algo, algo)} | {n} | "
            f"{fmt(df['return_mean'].mean(), df['return_mean'].std() if n > 1 else None)} | "
            f"{fmt(df['x_velocity_mean'].mean(), df['x_velocity_mean'].std() if n > 1 else None, 3)} | "
            f"{fmt(df['steps_mean'].mean(), df['steps_mean'].std() if n > 1 else None, 0)} | "
            f"{fmt(df['mean_sq_action_mean'].mean(), df['mean_sq_action_mean'].std() if n > 1 else None, 3)} | "
            f"{eff_cell} |")

    # ---- variance-reduction ablation ------------------------------------
    if ablations:
        env_note = f" on `{abl_env}`" if abl_env else ""
        lines += ["", f"## Variance-reduction ablation{env_note}", "",
                  "Our own REINFORCE. The two steps Lecture 07 proves, measured "
                  "rather than asserted. Returns are not comparable with the main "
                  "table above when the environment differs.", "",
                  "| Variant | Seeds | Return | Fwd velocity (m/s) |",
                  "|---|---|---|---|"]
        label = {"to-go_value": "reward-to-go + value baseline (full method)",
                 "to-go_none": "reward-to-go, no baseline",
                 "full_value": "full return + value baseline",
                 "full_none": "full return, no baseline"}
        for key in ["to-go_value", "to-go_none", "full_value", "full_none"]:
            rows = ablations.get(key)
            if not rows:
                continue
            d = pd.DataFrame(rows); n = len(d)
            lines.append(
                f"| {label.get(key, key)} | {n} | "
                f"{fmt(d['return_mean'].mean(), d['return_mean'].std() if n > 1 else None)} | "
                f"{fmt(d['x_velocity_mean'].mean(), d['x_velocity_mean'].std() if n > 1 else None, 3)} |")
        for key, rows in sorted(ablations.items()):
            if key in label or not rows:
                continue
            d = pd.DataFrame(rows); n = len(d)
            lines.append(f"| {key} | {n} | {fmt(d['return_mean'].mean())} | "
                         f"{fmt(d['x_velocity_mean'].mean(), None, 3)} |")

    # ---- robustness ------------------------------------------------------
    rpath = Path(args.robustness)
    if rpath.exists():
        rob = pd.read_csv(rpath)
        rob["algo"] = [parse_name(str(n))[0] for n in rob["name"]]
        cols = [(k, lv) for k in ["mass", "gravity", "noise"]
                for lv in sorted(rob[rob["perturbation"] == k]["level"].unique())
                if lv != sorted(rob[rob["perturbation"] == k]["level"].unique())[0]]
        # Absolute returns, not percentages. A retention ratio is meaningless
        # when the unperturbed baseline is near the floor and dominated by
        # variance: PPO's baseline is ~195 with a comparable s.d., which
        # produced "retains 412%" in an earlier version of this table.
        lines += ["", "## Robustness", "",
                  "Mean return over the evaluation episodes, no retraining. "
                  "Compare each row against its own unperturbed column.", "",
                  "| Policy | unperturbed | "
                  + " | ".join(f"{k} x{lv:g}" for k, lv in cols) + " |",
                  "|---" * (len(cols) + 2) + "|"]
        for algo in ORDER:
            sub = rob[rob["algo"] == algo]
            if sub.empty:
                continue
            base_rows = sub[(sub["perturbation"] == "mass") & (sub["level"] == 1.0)]
            base = base_rows["return_mean"].mean() if len(base_rows) else float("nan")
            cells = [f"{base:,.0f}" if base == base else ""]
            for k, lv in cols:
                r = sub[(sub["perturbation"] == k) & (sub["level"] == lv)]
                cells.append(f"{r['return_mean'].mean():,.0f}" if len(r) else "")
            lines.append(f"| {PRETTY.get(algo, algo)} | " + " | ".join(cells) + " |")
        lines += ["", "Read this with the main table. A policy whose unperturbed "
                  "return is already near the random floor cannot show a "
                  "meaningful drop, so only the A2C, REINFORCE and scripted rows "
                  "support a robustness claim."]

    # ---- wall clock ------------------------------------------------------
    lines += ["", "## Wall clock", "", "| Run | Steps | Minutes |", "|---|---|---|"]
    for run_dir in sorted(Path(args.runs).glob("*")):
        cfg = run_dir / "config.json"
        if not cfg.exists():
            continue
        c = json.loads(cfg.read_text())
        if "wall_clock_seconds" in c:
            lines.append(f"| {run_dir.name} | {c.get('total_timesteps', 0):,} | "
                         f"{c['wall_clock_seconds']/60:.1f} |")

    out = Path(args.out)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"[tables] {len(groups)} algorithms, {len(ablations)} ablations -> {out}")


if __name__ == "__main__":
    main()
